import 'package:material_ui/material_ui.dart';

import 'package:myportofolio_mobile/screens/education_form.dart';
import 'package:myportofolio_mobile/screens/project_form.dart';
import 'package:myportofolio_mobile/widgets/left_drawer.dart';
import 'package:myportofolio_mobile/widgets/project_card.dart';

class MyHomePage extends StatelessWidget {
  MyHomePage({super.key});

  final String npm = "2506656614";
  final String nama = "Della Permata Prasilda";
  final String kelas = "PBP A";

  final List<ItemHomepage> items = [
    ItemHomepage("Lihat Education", Icons.school, Colors.blue),
    ItemHomepage("Lihat Skills", Icons.code, Colors.green),
    ItemHomepage("Lihat Experience", Icons.work, Colors.orange.shade800),
    ItemHomepage("Lihat Proyek", Icons.folder, Colors.purple),
    ItemHomepage(
      "Tambah Proyek",
      Icons.add_circle,
      Colors.brown,
      pageBuilder: (context) => const ProjectFormPage(),
    ),
    ItemHomepage(
      "Tambah Education",
      Icons.school_outlined,
      Colors.teal,
      pageBuilder: (context) => const EducationFormPage(),
    ),
    ItemHomepage("Logout", Icons.logout, Colors.red),
  ];

  @override
  Widget build(BuildContext context) {
    // Scaffold menyediakan struktur visual dasar halaman (AppBar, Body, SnackBar).
    return Scaffold(
      // AppBar menampilkan bar bagian atas halaman aplikasi.
      appBar: AppBar(
        title: const Text(
          'MyPortfolio',
          style: TextStyle(
            color: Colors.white,
            fontWeight: FontWeight.bold,
          ),
        ),
        backgroundColor: Theme.of(context).colorScheme.primary,
        iconTheme: const IconThemeData(color: Colors.white),
      ),
      // Drawer menu untuk navigasi antarhalaman.
      drawer: const LeftDrawer(),
      body: SingleChildScrollView(
        child: Padding(
          padding: const EdgeInsets.all(16.0),
